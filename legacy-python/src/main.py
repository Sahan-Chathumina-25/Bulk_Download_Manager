"""Application entry point.

``build_app()`` performs the whole bootstrap (logging, database, repository,
settings, manager, MainWindow, interrupted-download recovery) and is
reusable when a ``QApplication`` already exists. ``main()`` wraps it in the
normal Qt event loop.

User data (database, logs, defaults) always resolves through
:mod:`src.utils.paths`, which deliberately ignores the PyInstaller bundle
directory (``sys._MEIPASS``) — nothing generated by the user is ever
written into a (possibly read-only) frozen bundle.
"""

from __future__ import annotations

import logging
import sys
from collections.abc import Iterable

from PySide6.QtWidgets import QApplication, QMessageBox

from src.app.main_window import MainWindow
from src.app.theme import apply_theme
from src.core.download_manager import DownloadManager
from src.database.connection import init_db
from src.database.models import DownloadState, Settings
from src.database.repository import DownloadRepository
from src.utils import paths
from src.utils.logging_config import setup_logging

__all__ = ["build_app", "main"]

log = logging.getLogger(__name__)


def build_app() -> MainWindow:
    """Construct the fully wired application window.

    Creates logging, the SQLite database, the repository, validated settings,
    the :class:`DownloadManager`, and the :class:`MainWindow` (which hooks the
    manager callbacks into its Qt relay internally). After construction,
    interrupted downloads from a previous session are recovered; when rows
    remain resumable, the user is asked to resume them immediately.

    Returns:
        A shown-ready, hidden :class:`MainWindow`.
    """
    setup_logging()
    if QApplication.instance() is None:
        # Make build_app() usable in test/embedded contexts without main().
        app = QApplication(sys.argv)
        apply_theme(app)

    db = init_db(paths.db_path())
    repository = DownloadRepository(db)
    settings = repository.get_settings() or Settings()
    manager = DownloadManager(settings, repository)
    window = MainWindow(manager, repository, settings)

    try:
        recovered = repository.recover_interrupted()
    except Exception:  # noqa: BLE001 - startup recovery must not crash the GUI
        log.exception("startup recovery failed; continuing without reconcile")
        recovered = []
    resumable = [
        record.id
        for record in recovered
        if record.state is DownloadState.INTERRUPTED and record.id is not None
    ]
    window.pending_interrupted = resumable
    if resumable:
        log.info("%d interrupted download(s) recovered from the last session", len(resumable))
        _offer_resume(window, resumable)
    return window


def _offer_resume(window: MainWindow, download_ids: list[int]) -> None:
    """Ask the user to resume downloads interrupted by the previous session."""
    answer = QMessageBox.question(
        window,
        "Resume interrupted downloads?",
        f"{len(download_ids)} download(s) were interrupted when the application "
        "last closed. Resume them now?",
        QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
        QMessageBox.StandardButton.Yes,
    )
    if answer != QMessageBox.StandardButton.Yes:
        return
    for download_id in download_ids:
        try:
            window._manager.resume(download_id)  # noqa: SLF001 - same-app component
        except (ValueError, RuntimeError) as exc:
            log.warning("could not resume download %d: %s", download_id, exc)
            window.pending_interrupted = [
                i for i in window.pending_interrupted if i != download_id
            ]
    log.info("resumed %d interrupted download(s)", len(download_ids))


def main(argv: Iterable[str] | None = None) -> int:
    """Launch the PySide6 application event loop.

    Args:
        argv: CLI arguments (defaults to ``sys.argv[1:]`` when ``None``).

    Returns:
        The QApplication exit code.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    del args  # no CLI switches yet

    setup_logging()
    app = QApplication.instance() or QApplication(sys.argv)
    apply_theme(app)

    window = build_app()
    window.show()
    code = app.exec()
    log.info("application exited with code %d", code)
    return code


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
